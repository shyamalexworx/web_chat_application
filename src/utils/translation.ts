function humanizeKey(key: string): string {
  return key
    .replace(/_/g, ' ')
    .replace(/\b\w/g, (c) => c.toUpperCase());
}

export function translateChannelName(name: string, targetLang: string): string {
  if (!name || targetLang === 'en') return name;
  const clean = name.replace(/^#/, '').replace(/[-_]+/g, ' ').trim();
  return translateTextSync(clean, targetLang);
}

export function translateEntityName(name: string, targetLang: string): string {
  if (!name || targetLang === 'en') return name;
  return translateTextSync(name.trim(), targetLang);
}

export function getTranslation(key: string, lang: string): string {
  if (lang === 'en' || !lang) {
    return UI_TRANSLATIONS.en?.[key] || humanizeKey(key);
  }
  const translated = UI_TRANSLATIONS[lang]?.[key];
  if (translated) {
    return translated;
  }
  const fallback = UI_TRANSLATIONS.en?.[key] || humanizeKey(key);
  return translateTextSync(fallback, lang);
}

// ==============================================================================
// DYNAMIC MULTI-LANGUAGE REALTIME TRANSLATION ENGINE
// Translates any arbitrary chat message, topic, or dynamic text via Google Translate
// Supported by ultra-fast in-memory and persistent localStorage caching
// ==============================================================================

const CACHE_STORAGE_KEY = 'pulsechat_translation_cache_v2';
const translationMemoryCache = new Map<string, string>();

// Initialize memory cache from localStorage
try {
  if (typeof window !== 'undefined' && window.localStorage) {
    const raw = localStorage.getItem(CACHE_STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      for (const [k, v] of Object.entries(parsed)) {
        if (typeof v === 'string') translationMemoryCache.set(k, v);
      }
    }
  }
} catch (e) {}

// Event listeners for translation updates
const listeners = new Set<() => void>();
export function subscribeToTranslations(listener: () => void): () => void {
  listeners.add(listener);
  return () => {
    listeners.delete(listener);
  };
}

function notifyTranslationListeners() {
  listeners.forEach((fn) => {
    try {
      fn();
    } catch (e) {}
  });
}

function persistCache() {
  try {
    if (typeof window !== 'undefined' && window.localStorage) {
      const obj: Record<string, string> = {};
      let count = 0;
      for (const [k, v] of translationMemoryCache.entries()) {
        obj[k] = v;
        count++;
        if (count > 800) break;
      }
      localStorage.setItem(CACHE_STORAGE_KEY, JSON.stringify(obj));
    }
  } catch (e) {}
}

const pendingRequests = new Set<string>();

/**
 * Check if a text is already translated in cache
 */
export function hasTranslation(text: string, targetLang: string): boolean {
  if (!text || targetLang === 'en') return true;
  return translationMemoryCache.has(`${targetLang}:::${text.trim()}`);
}

/**
 * Asynchronously fetch translation from Google Translate API
 */
export async function fetchGoogleTranslate(text: string, targetLang: string): Promise<string> {
  const trimmed = text.trim();
  if (!trimmed || targetLang === 'en') return text;

  const cacheKey = `${targetLang}:::${trimmed}`;
  if (translationMemoryCache.has(cacheKey)) {
    return translationMemoryCache.get(cacheKey)!;
  }

  // Handle markdown code blocks - preserve code verbatim
  if (trimmed.includes('```')) {
    const parts = trimmed.split(/(```[\s\S]*?```)/g);
    const translatedParts = await Promise.all(
      parts.map(async (part) => {
        if (part.startsWith('```') && part.endsWith('```')) {
          return part;
        }
        if (!part.trim()) return part;
        return fetchGoogleTranslate(part, targetLang);
      })
    );
    const result = translatedParts.join('');
    translationMemoryCache.set(cacheKey, result);
    persistCache();
    notifyTranslationListeners();
    return result;
  }

  try {
    const url = `https://translate.googleapis.com/translate_a/single?client=gtx&sl=auto&tl=${encodeURIComponent(
      targetLang
    )}&dt=t&q=${encodeURIComponent(trimmed)}`;
    const res = await fetch(url);
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const data = await res.json();
    if (Array.isArray(data) && Array.isArray(data[0])) {
      const translated = data[0].map((item: any) => item[0]).join('');
      if (translated) {
        translationMemoryCache.set(cacheKey, translated);
        persistCache();
        notifyTranslationListeners();
        return translated;
      }
    }
  } catch (err) {
    // Non-fatal, will retry next render or stay with original
  }

  return text;
}

/**
 * Synchronous translate lookup with background auto-fetching
 */
export function translateTextSync(text: string, targetLang: string): string {
  if (!text || targetLang === 'en') return text;
  const trimmed = text.trim();
  if (!trimmed) return text;

  const cacheKey = `${targetLang}:::${trimmed}`;
  if (translationMemoryCache.has(cacheKey)) {
    return translationMemoryCache.get(cacheKey)!;
  }

  // Trigger background fetch if not already in flight
  if (!pendingRequests.has(cacheKey) && typeof window !== 'undefined') {
    pendingRequests.add(cacheKey);
    fetchGoogleTranslate(trimmed, targetLang).finally(() => {
      pendingRequests.delete(cacheKey);
    });
  }

  return text;
}

export const translateText = translateTextSync;

/**
 * Batch translate multiple texts in parallel
 */
export async function batchTranslate(texts: string[], targetLang: string): Promise<void> {
  if (targetLang === 'en' || !texts.length) return;
  const toFetch = Array.from(new Set(texts.map((t) => (t || '').trim()))).filter(
    (t) => t && !translationMemoryCache.has(`${targetLang}:::${t}`) && !pendingRequests.has(`${targetLang}:::${t}`)
  );

  if (!toFetch.length) return;

  await Promise.all(
    toFetch.map((t) => {
      const cacheKey = `${targetLang}:::${t}`;
      pendingRequests.add(cacheKey);
      return fetchGoogleTranslate(t, targetLang).finally(() => {
        pendingRequests.delete(cacheKey);
      });
    })
  );
}
